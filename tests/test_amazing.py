import subprocess
import sys

import pytest

from config_parser import config_validator
from mazegen import MazeGenerator
from mazegen.core import Step


def check_analyzer_verdict(output_file: str, verdict: str) -> None:
    """Check the verdict of the maze analyzer (provided with the subject)

    Tests: shared walls, connectivity, perfect or playable maze.
    Not tested: border walls, 3x3 areas, "42" drawing, solution path.
    """
    # the analyzer exits 0 even on a bad verdict: read what it prints
    analyzer = subprocess.run(
        [sys.executable, "tests/maze_analyzer.py", output_file],
        capture_output=True,
        text=True,
    )
    # hidden by pytest when the test passes, see it with: pytest -rP
    print(analyzer.stdout)
    assert verdict in analyzer.stdout


def build_maze(config_file: str) -> MazeGenerator:
    """Build the maze of a config file with MazeGenerator."""
    config = config_validator(config_file)
    return MazeGenerator(
        config.WIDTH,
        config.HEIGHT,
        config.ENTRY,
        config.EXIT,
        config.PERFECT,
        config.SEED,
    )


def read_output(config_file: str) -> list[str]:
    """Read the lines of the output file written by the app."""
    config = config_validator(config_file)
    with open(config.OUTPUT_FILE) as f:
        return f.read().splitlines()


def check_walls(config_file: str) -> None:
    """Check that the app and MazeGenerator have the same walls."""
    maze = build_maze(config_file)
    lines = read_output(config_file)

    # compare the walls of the facade with their hex representation
    # in the output file generated by the app, line by line
    for y, row in enumerate(maze.grid):
        walls = ""
        for cell in row:
            walls += hex(cell.wall)[2:]
        assert walls == lines[y]


def check_solution(config_file: str) -> None:
    """Check that the app and MazeGenerator find the same path."""
    maze = build_maze(config_file)
    lines = read_output(config_file)

    # compare the solution path (last line of the file)
    path = ""
    for i in range(len(maze.solution) - 1):
        ax, ay = maze.solution[i]
        bx, by = maze.solution[i + 1]
        path += Step((bx - ax, by - ay)).name
    assert path == lines[-1]


class MazeChecks:
    """Tests shared by every config, one class per config below.

    Not prefixed with "Test": pytest does not run it on its own.
    """

    CONFIG: str

    # test_app_runs writes the output file read by the next tests:
    # they rely on the order of this class. If the app fails or if one
    # test is run alone, they read an old file or find none.
    def test_app_runs(self) -> None:
        """Run the app with the Makefile."""
        # its output is captured: the animation would flood the pytest output
        app = subprocess.run(
            ["make", "run", "CONFIG=" + self.CONFIG],
            capture_output=True,
            text=True,
        )
        assert app.returncode == 0, app.stderr

    def test_walls_match_generator(self) -> None:
        """Compare the walls, only possible with a SEED."""
        # "is None": 0 is a valid seed
        if config_validator(self.CONFIG).SEED is None:
            pytest.skip("no SEED: the two mazes are random")
        check_walls(self.CONFIG)

    def test_solution_matches_generator(self) -> None:
        """Compare the solution paths, only possible with a SEED."""
        if config_validator(self.CONFIG).SEED is None:
            pytest.skip("no SEED: the two mazes are random")
        check_solution(self.CONFIG)

    def test_analyzer_verdict(self) -> None:
        """Expect the analyzer verdict that matches PERFECT."""
        config = config_validator(self.CONFIG)
        if config.PERFECT:
            verdict = "Verdict: PERFECT maze"
        else:
            verdict = "Verdict: Pac-Man-USABLE"
        check_analyzer_verdict(config.OUTPUT_FILE, verdict)


class TestPerfect(MazeChecks):
    """Perfect maze."""

    CONFIG = "tests/perfect-config.txt"


class TestImperfect(MazeChecks):
    """Imperfect maze."""

    CONFIG = "tests/imperfect-config.txt"
